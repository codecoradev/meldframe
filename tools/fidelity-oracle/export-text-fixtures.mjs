// Writes the oracle fixtures that hold text as JSON for the text measurer conformance suite of `meldframe-layout`
// (`docs/fidelity-contract.md` section 6a). The suite lays each file out with a reference measurer and asks a
// measurer under test the same questions, so it needs the nodes and nothing else; no browser runs.
//
//   node export-text-fixtures.mjs           rewrite crates/core/meldframe-layout/tests/fixtures/oracle_texts.json
//   node export-text-fixtures.mjs --check   exit 1 when that file differs from what the fixtures give now
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import fixtures from './fixtures.mjs';

export const TARGET = path.join(path.dirname(fileURLToPath(import.meta.url)), '../../crates/core/meldframe-layout/tests/fixtures/oracle_texts.json');

/** The JSON text: the fixtures with at least one text node, one node to a line. */
export function render() {
  const keep = fixtures.filter((f) => f.nodes.some((n) => n.type === 'text'));
  const lines = keep.map((f) => `  {"name":${JSON.stringify(f.name)},"nodes":[\n${f.nodes.map((n) => `    ${JSON.stringify(n)}`).join(',\n')}\n  ]}`);
  const source = 'Generated by tools/fidelity-oracle/export-text-fixtures.mjs from fixtures.mjs: the fixtures that hold text, as the layout core reads them. Do not edit by hand.';
  return `{"source":${JSON.stringify(source)},"fixtures":[\n${lines.join(',\n')}\n]}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (have !== text) {
      console.error(`${TARGET} is out of date: run node export-text-fixtures.mjs and commit the result`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(TARGET, text);
  }
}
