#!/bin/sh
# Self-test of the CI check scripts: good and bad examples for each. Exit 0 when all behave.
# Run from anywhere: sh scripts/ci/selftest.sh
set -u
here="$(cd "$(dirname "$0")" && pwd)"
fail=0

# expect <label> <want: clean|reject> <text>   (Message Standard)
msg() {
  out=$(printf '%s\n' "$3" | sh "$here/message-patterns.sh")
  if [ -z "$out" ]; then got=clean; else got=reject; fi
  if [ "$got" = "$2" ]; then echo "pass  message: $1"; else echo "FAIL  message: $1 (wanted $2, got $got)"; fail=1; fi
}
msg "plain conventional commit" clean "feat(core): add the submit-a-command interface

Signed-off-by: A Person <a@example.com>"
msg "body mentioning Claude in prose" clean "docs: explain how agents such as Claude connect over MCP"
msg "Co-Authored-By trailer" reject "feat: x

Co-Authored-By: Someone <noreply@example.com>"
msg "Co-authored-by lowercase" reject "fix: x

co-authored-by: Someone <noreply@example.com>"
msg "Claude-Session trailer" reject "feat: x

Claude-Session: abc123"
msg "claude.ai/code link" reject "See https://claude.ai/code/session_01ABC for context"
msg "Generated with a tool link" reject "Generated with [Claude Code](https://example.com)"
msg "Generated with bold" reject "**Generated with** Claude Code"
msg "Generated by a tool name" reject "Generated by ChatGPT"
msg "generated with a build tool is fine" clean "chore: the file is generated with protoc and committed"

# branch <name> <want: ok|bad>
br() {
  if sh "$here/branch-name.sh" "$1" >/dev/null 2>&1; then got=ok; else got=bad; fi
  if [ "$got" = "$2" ]; then echo "pass  branch: $1"; else echo "FAIL  branch: $1 (wanted $2, got $got)"; fail=1; fi
}
for p in feat fix docs chore refactor perf test ci build release; do br "$p/some-change" ok; done
br develop ok; br main ok
br "security/x" bad; br "feature/x" bad; br "feat/" bad; br "feat/Upper" bad; br "my-branch" bad; br "claude/foo" bad

# body <label> <want: ok|bad> <text>
body() {
  if printf '%s\n' "$3" | sh "$here/pr-body.sh" - >/dev/null 2>&1; then got=ok; else got=bad; fi
  if [ "$got" = "$2" ]; then echo "pass  pr body: $1"; else echo "FAIL  pr body: $1 (wanted $2, got $got)"; fail=1; fi
}
full="## What
A thing.

## Why
A reason.

## Changes
- one

## Testing
Ran it."
body "all four sections" ok "$full"
body "missing Testing" bad "## What
a
## Why
b
## Changes
c"
body "empty Why" bad "## What
a
## Why

## Changes
c
## Testing
d"
body "comment-only Changes" bad "## What
a
## Why
b
## Changes
<!-- list the changes -->
## Testing
d"
body "heading case ignored" ok "## what
a
## WHY
b
## changes
c
## testing
d"
body "empty body" bad ""

# gate <name> <want: pending|run>  (against a temporary pending list)
tmp=$(mktemp -d); mkdir -p "$tmp/scripts/ci" "$tmp/.gitea"
cp "$here/gate.sh" "$tmp/scripts/ci/gate.sh"
printf '# c\nfmt\ndeps-check # why\n' > "$tmp/.gitea/ci-pending.txt"
gt() {
  : > "$tmp/out"; GITHUB_OUTPUT="$tmp/out" sh "$tmp/scripts/ci/gate.sh" "$1" >/dev/null
  if grep -q 'pending=true' "$tmp/out"; then got=pending; else got=run; fi
  if [ "$got" = "$2" ]; then echo "pass  gate: $1 is $got"; else echo "FAIL  gate: $1 (wanted $2, got $got)"; fail=1; fi
}
gt fmt pending; gt deps-check pending; gt clippy run; gt "fmt-extra" run
# once a workspace exists, a pending Cargo gate is an error
printf '# c\nfmt\n' > "$tmp/.gitea/ci-pending.txt"; : > "$tmp/Cargo.toml"; : > "$tmp/out"
if GITHUB_OUTPUT="$tmp/out" sh "$tmp/scripts/ci/gate.sh" fmt >/dev/null 2>&1; then echo "FAIL  gate: fmt pending with a workspace should error"; fail=1; else echo "pass  gate: fmt pending with a workspace errors"; fi
rm -rf "$tmp"

[ "$fail" -eq 0 ] && echo "all checks behave" || echo "SELFTEST FAILED"
exit "$fail"
